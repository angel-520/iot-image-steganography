import { chromium } from '../frontend/node_modules/playwright/index.mjs';
import dgram from 'node:dgram';
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
const probe=dgram.createSocket('udp4');
await new Promise(resolve=>probe.bind(0,'127.0.0.1',resolve));const port=probe.address().port;probe.close();
const browser=await chromium.launch({channel:'msedge',headless:true});
let receiverPage;
try {
  const a=await browser.newPage({viewport:{width:1440,height:1080}});
  const b=await browser.newPage({viewport:{width:1440,height:1080}});
  receiverPage=b;
  const errors=[];for(const p of[a,b])p.on('pageerror',e=>errors.push(e.message));
  const choose=async(p,label,option)=>{await p.locator('.ant-select').filter({has:p.getByRole('combobox',{name:label,exact:true})}).locator('.ant-select-selector').click();await p.locator('.ant-select-dropdown:visible .ant-select-item-option-content').getByText(option,{exact:true}).click();};
  await Promise.all([a.goto('http://127.0.0.1:8017/network-lab'),b.goto('http://127.0.0.1:8018/network-lab')]);
  for(const p of[a,b])await p.getByRole('tab',{name:'双机 / 公网',exact:true}).click();
  await b.getByRole('tab',{name:'接收消息',exact:true}).click();
  await b.getByRole('textbox',{name:'允许的发送方 IP',exact:true}).fill('127.0.0.1');
  await b.getByRole('spinbutton',{name:'本机接收端口',exact:true}).fill(String(port));
  await choose(b,'接收协议','TCP · 分块文件 / 文字传输');
  await b.getByRole('button',{name:'生成共享口令',exact:true}).click();
  const key=await b.getByLabel('接收共享口令',{exact:true}).inputValue();
  await b.getByRole('button',{name:'开始接收',exact:true}).click();
  await b.getByText('正在接收',{exact:true}).waitFor();
  await a.getByRole('textbox',{name:'接收方 IP 地址',exact:true}).fill('127.0.0.1');
  await a.getByRole('spinbutton',{name:'接收方端口',exact:true}).fill(String(port));
  await a.getByLabel('发送共享口令',{exact:true}).fill(key);
  await a.getByRole('button',{name:'保存接收方设置',exact:true}).click();
  await a.getByText(`127.0.0.1:${port}`,{exact:true}).first().waitFor();
  await choose(a,'发送内容类型','图片 / 音频 / 视频 / 任意文件');
  const payload=Buffer.from(Array.from({length:8192},(_,i)=>(i*17+3)%256));
  const hash=createHash('sha256').update(payload).digest('hex');
  await a.locator('input[type=file]').setInputFiles({name:'课程资料.bin',mimeType:'application/octet-stream',buffer:payload});
  await a.getByText('课程资料.bin',{exact:true}).waitFor();
  await choose(a,'传输加密类型','ChaCha20-Poly1305');
  await a.getByRole('spinbutton',{name:'发送速率',exact:true}).fill('0.5');
  await a.getByRole('spinbutton',{name:'发送速率',exact:true}).press('Tab');
  await a.getByRole('button',{name:/发送给对方/}).click();
  await a.getByText('对方已接收',{exact:true}).waitFor();
  await b.getByText('课程资料.bin',{exact:true}).waitFor();
  const fileLink=b.locator('a').filter({hasText:'下载原始文件'}).first();
  const received=await b.request.get(new URL(await fileLink.getAttribute('href'),b.url()).href);
  if(!(await received.body()).equals(payload))throw Error('TCP downloaded bytes differ');
  await b.getByText(`SHA-256 · ${hash}`,{exact:true}).waitFor();
  const pcapLink=b.locator('a').filter({hasText:'下载接收轨迹 PCAP'}).first();
  const capture=await b.request.get(new URL(await pcapLink.getAttribute('href'),b.url()).href);
  await fs.writeFile('.qa/tcp-received.pcap',await capture.body());
  for(const [p,name]of[[a,'file-sender'],[b,'file-receiver']]){await p.evaluate(()=>window.scrollTo(0,0));await p.waitForTimeout(350);await p.screenshot({path:`.qa/${name}.png`,fullPage:true});}
  await b.getByRole('button',{name:'停止接收',exact:true}).click();await b.getByText('已停止',{exact:true}).waitFor();
  await choose(b,'接收协议','UDP · 隐写或分块传输');await b.getByLabel('接收共享口令',{exact:true}).fill(key);
  await b.getByRole('button',{name:'开始接收',exact:true}).click();await b.getByText('正在接收',{exact:true}).waitFor();
  await choose(a,'发送协议','UDP');await choose(a,'传输加密类型','AES-256-GCM');
  await a.getByRole('spinbutton',{name:'UDP 窗口',exact:true}).fill('8');
  await a.getByRole('button',{name:/发送给对方/}).click();await a.getByText('对方已接收',{exact:true}).waitFor();
  await b.waitForFunction(()=>document.querySelectorAll('.network-incoming').length===2);
  await b.getByRole('button',{name:'停止接收',exact:true}).click();
  await b.setViewportSize({width:390,height:844});await b.waitForTimeout(400);await b.screenshot({path:'.qa/file-mobile.png',fullPage:true});
  if(await b.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2))throw Error('Mobile overflow');
  if(errors.length)throw Error(errors.join('; '));
  console.log(JSON.stringify({tcpBinaryExact:true,udpBinaryReceived:true,cipherAndRateControls:true,pcapDownloaded:true,mobileNoOverflow:true,pageErrors:errors}));
}finally{if(receiverPage)await receiverPage.request.post('http://127.0.0.1:8018/api/network-lab/receiver/stop').catch(()=>{});await browser.close();}
