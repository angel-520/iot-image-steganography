import { chromium } from '../frontend/node_modules/playwright/index.mjs';
import path from 'node:path';
import fs from 'node:fs/promises';
const browser = await chromium.launch({channel:'msedge',headless:true});
try {
  const page = await browser.newPage({viewport:{width:1440,height:1080}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  let result;
  page.on('response',async r=>{if(r.url().includes('/api/tasks/'))try{const d=await r.json();if(d.status==='completed'&&d.result?.baseline)result=d.result;}catch{}});
  const select=async(name,text)=>{await page.locator('.ant-select').filter({has:page.getByRole('combobox',{name,exact:true})}).locator('.ant-select-selector').click();await page.getByText(text,{exact:true}).last().click();};
  const shot=async name=>{await page.evaluate(()=>window.scrollTo(0,0));await page.waitForTimeout(400);await page.screenshot({path:path.resolve(`.qa/${name}.png`),fullPage:true});};
  await page.goto('http://127.0.0.1:8017/network-lab');
  await page.getByRole('heading',{name:'在流量之间，观察信息'}).waitFor();
  await page.getByRole('textbox',{name:'网络秘密文本'}).fill('网络浏览器往返 🔐');
  await page.getByRole('spinbutton',{name:'网络抖动',exact:true}).fill('15');
  await page.getByRole('spinbutton',{name:'网络抖动',exact:true}).press('Tab');
  await page.getByRole('button',{name:/开始离线实验/}).click();
  await page.getByText('网络浏览器往返 🔐',{exact:true}).waitFor();
  await page.getByRole('tab',{name:'隐蔽信道检测',exact:true}).click();
  await page.getByText('模型评估 · 独立合成测试集',{exact:true}).waitFor();
  await shot('network-timing-detection');
  await page.getByRole('tab',{name:'扰动后流量',exact:true}).click();
  await page.getByText('未完整恢复秘密信息',{exact:true}).waitFor();
  await shot('network-timing-impaired');
  await select('网络信道','UDP 数据包长度');
  await select('传输方式','本机回环 UDP');
  await page.getByRole('button',{name:/开始 UDP 传输/}).click();
  await page.getByText(/UDP 传输完成/).waitFor();
  await shot('network-loopback-length');
  if(result?.channel!=='length'||!result?.transport)throw Error('Missing real UDP result');
  const pcap=await page.request.get(new URL(result.baseline.pcap.url,page.url()).href);
  await fs.writeFile('.qa/network_baseline.pcap',await pcap.body());
  await page.getByRole('tab',{name:'协议字段 · 离线',exact:true}).click();
  await select('网络信道','TCP · Sequence Number');
  await page.getByRole('button',{name:/生成 PCAP 并提取/}).click();
  await page.getByText('ISTG 网络实验',{exact:true}).waitFor();
  await shot('network-offline-fields');
  await page.getByRole('tab',{name:'流量分析与鲁棒性',exact:true}).click();
  await page.locator('input[type=file]').setInputFiles(path.resolve('.qa/network_baseline.pcap'));
  await page.getByText('network_baseline.pcap',{exact:true}).waitFor();
  await select('网络信道','UDP 数据包长度');
  await page.getByRole('button',{name:'分析流量并尝试恢复',exact:true}).click();
  await page.getByText('网络浏览器往返 🔐',{exact:true}).waitFor();
  await page.getByRole('tab',{name:'协议字段明细',exact:true}).click();
  await shot('network-pcap-analysis');
  await page.setViewportSize({width:390,height:844});
  await shot('network-mobile');
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2))throw Error('Mobile horizontal overflow');
  if(errors.length)throw Error(errors.join('; '));
  console.log(JSON.stringify({timingSimulation:true,actualUdpLength:true,offlineTCP:true,pcapUploadRecovery:true,detectionCharts:true,mobileNoOverflow:true,pageErrors:errors}));
} finally {await browser.close();}
