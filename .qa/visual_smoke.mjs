import { chromium } from '../frontend/node_modules/playwright/index.mjs';
import path from 'node:path';
const browser = await chromium.launch({channel:'msedge',headless:true});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1080}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const shot=async name=>{await page.evaluate(()=>window.scrollTo(0,0));await page.waitForTimeout(350);await page.screenshot({path:path.resolve(`.qa/${name}.png`),fullPage:true});};
  await page.goto('http://127.0.0.1:8017/multimodal');
  await page.getByText('视频',{exact:true}).click();
  await page.locator('input[type=file]').first().setInputFiles(path.resolve('.qa/cover.mp4'));
  await page.getByText('cover.mp4',{exact:true}).waitFor();
  await page.getByRole('textbox',{name:'秘密文字',exact:true}).fill('视频帧验证');
  await page.getByText('AES-256-GCM',{exact:true}).click();
  await page.getByText('不加密',{exact:true}).click();
  await page.getByRole('button',{name:/开始嵌入/}).click();
  await page.getByText('提取验证通过',{exact:true}).waitFor();
  await page.locator('.mm-video').evaluate(video=>new Promise((resolve,reject)=>{if(video.readyState>=2)return resolve();video.addEventListener('loadeddata',resolve,{once:true});video.addEventListener('error',()=>reject(Error('Video preview playback failed')),{once:true});}));
  const video=await page.locator('.mm-video').evaluate(v=>({width:v.videoWidth,height:v.videoHeight,duration:v.duration}));
  if(!video.width)throw Error('Video preview has no decoded pixels');
  await page.getByRole('slider').focus();await page.getByRole('slider').press('ArrowRight');
  await page.waitForFunction(()=>document.querySelector('.ant-slider-handle')?.getAttribute('aria-valuenow') === '1');
  await shot('video-desktop');
  await page.getByText('文本',{exact:true}).click();
  await page.locator('input[type=file]').first().setInputFiles(path.resolve('.qa/cover.txt'));
  await page.getByText('cover.txt',{exact:true}).waitFor();
  await page.getByRole('button',{name:/开始嵌入/}).click();
  await page.getByText('提取验证通过',{exact:true}).waitFor();
  await page.getByText('隐藏字符可视化（前 1024 位）',{exact:true}).waitFor();
  await shot('text-desktop');
  await page.getByRole('tab',{name:'安全攻防实验',exact:true}).click();
  await page.locator('input[type=file]').first().setInputFiles(path.resolve('.qa/stego.wav'));
  await page.getByText('stego.wav',{exact:true}).waitFor();
  await page.getByRole('button',{name:'开始攻击测试',exact:true}).click();
  await page.getByText('完整恢复',{exact:true}).waitFor();
  await shot('attack-desktop');
  await page.getByRole('tab',{name:'多载体协同',exact:true}).click();
  await page.getByText('载体 3',{exact:true}).waitFor();
  await shot('cooperative-desktop');
  await page.setViewportSize({width:390,height:844});
  await shot('cooperative-mobile');
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2);
  if(overflow)throw Error('Mobile page overflows horizontally');
  console.log(JSON.stringify({videoPreview:video,textVisualization:true,attackUI:true,cooperativeUI:true,mobileNoOverflow:true,pageErrors:errors}));
} finally {await browser.close();}
